# ---------------------------------------------------------------
# Enterprise Assistant: Day 1
# A minimal API: send a question, get an LLM answer back,
# plus latency and token counts for cost tracking.
# ---------------------------------------------------------------

import os      # read environment variables (our settings from .env)
import time    # precise timer for measuring latency

from dotenv import load_dotenv                  # loads the .env file into environment variables
from fastapi import FastAPI, HTTPException      # web framework + a way to return clean HTTP errors
from openai import OpenAI                       # LLM client; works with Ollama, Azure OpenAI, Databricks
from pydantic import BaseModel, Field           # data shapes with automatic validation

# --- Configuration ---------------------------------------------

load_dotenv()  # read .env so os.getenv() can see LLM_BASE_URL, LLM_API_KEY, LLM_MODEL

# One LLM client, created once at startup and reused for every request (faster than reconnecting).
# base_url = where to send requests (Ollama's OpenAI-compatible endpoint locally).
# api_key  = Ollama ignores it, but the library requires a value; a real key for Azure OpenAI later.
client = OpenAI(
    base_url=os.getenv("LLM_BASE_URL"),
    api_key=os.getenv("LLM_API_KEY"),
)

# Which model to use. Falls back to llama3.2 if .env doesn't set it.
MODEL = os.getenv("LLM_MODEL", "llama3.2")

# The web application. uvicorn looks for this variable: `uvicorn app.main:app`.
# title/version show up on the auto-generated /docs page.
app = FastAPI(title="Enterprise Assistant", version="0.1.0")


# --- Request and response schemas ------------------------------

class AskRequest(BaseModel):
    """What a valid request must look like: {"question": "..."}"""

    # ...            -> required field
    # min_length=1   -> rejects empty questions
    # max_length=2000 -> rejects huge inputs (protects against token-cost abuse)
    # Invalid input is rejected automatically with HTTP 422, before any LLM call is made.
    question: str = Field(..., min_length=1, max_length=2000)


class AskResponse(BaseModel):
    """Exactly what the API returns: typed and predictable for any caller."""

    answer: str                       # the LLM's reply
    model: str                        # which model answered (useful when comparing models)
    latency_ms: int                   # how long the LLM call took, in milliseconds
    input_tokens: int | None = None   # tokens sent to the model (cost)
    output_tokens: int | None = None  # tokens generated by the model (cost)
                                      # Optional: some providers don't return usage.


# --- Endpoints -------------------------------------------------

@app.get("/health")
def health():
    """Liveness check used by load balancers and monitoring tools."""
    return {"status": "ok", "model": MODEL}


@app.post("/ask", response_model=AskResponse)
def ask(req: AskRequest):
    """Send the question to the LLM and return the answer with latency and token usage."""

    # FastAPI has already parsed and validated the JSON into `req` at this point.

    start = time.perf_counter()  # start the timer (most precise clock for durations)

    try:
        # Standard chat-completions call: send a list of messages, get a reply.
        resp = client.chat.completions.create(
            model=MODEL,
            messages=[
                # system = hidden instructions that shape behaviour (role, tone, length).
                # "2-4 sentences" keeps answers short, which also keeps output-token cost down.
                {
                    "role": "system",
                    "content": "You are a concise enterprise data assistant. Answer in 2-4 sentences.",
                },
                # user = the actual question from the request.
                {"role": "user", "content": req.question},
            ],
            # temperature=0 -> always pick the most likely tokens, so answers are near-deterministic.
            # Right for factual enterprise questions; higher values suit creative writing.
            temperature=0,
        )
    except Exception as e:
        # The LLM call failed (Ollama stopped, model missing, timeout...).
        # 502 Bad Gateway = "a service I depend on failed": a clean error instead of a crash.
        raise HTTPException(status_code=502, detail=f"LLM call failed: {e}")

    usage = resp.usage  # token counts reported by the provider (may be None)

    return AskResponse(
        # choices is a list (a model can return several alternatives); we take the first.
        answer=resp.choices[0].message.content,
        model=MODEL,
        # elapsed seconds x 1000 = milliseconds, as a whole number
        latency_ms=int((time.perf_counter() - start) * 1000),
        # record token counts if the provider sent them; otherwise None (no crash)
        input_tokens=usage.prompt_tokens if usage else None,
        output_tokens=usage.completion_tokens if usage else None,
    )
